template <typename T>
constexpr T parse(const char* s, int expectBits) {
  T v = 0;
  int bits = 0;
  for (size_t i = 0; s[i]; ++i) {
    if (s[i] == ' ') continue;
    v = T(v << 1) | T(s[i] == '#' ? 1 : 0);
    ++bits;
  }
  return bits == expectBits ? v : T(~T(0));  // ~0 = Formatfehler, per static_assert geprüft
}

