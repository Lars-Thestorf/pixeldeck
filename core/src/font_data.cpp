template <typename T, int Bits>
constexpr std::array<T, 95> build(const char* const (&src)[95]) {
  std::array<T, 95> out{};
  for (size_t i = 0; i < 95; ++i) out[i] = parse<T>(src[i], Bits);
  return out;
}

template <typename T, size_t N>
constexpr bool allValid(const std::array<T, N>& a) {
  for (size_t i = 0; i < N; ++i)
    if (a[i] == T(~T(0))) return false;
  return true;
}

